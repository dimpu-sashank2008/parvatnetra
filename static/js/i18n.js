let currentPortalLang = 'en';

function setPortalLanguage(langCode) {
    let lang = langCode || localStorage.getItem('parvat_lang') || 'en';
    if (!PARVAT_I18N[lang]) lang = 'en';
    currentPortalLang = lang;
    try {
        localStorage.setItem('parvat_lang', lang);
    } catch(e){}

    const dict = PARVAT_I18N[lang] || PARVAT_I18N.en;

    // 1. Update text of all [data-i18n] elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerText = dict[key];
        } else if (PARVAT_I18N.en[key]) {
            el.innerText = PARVAT_I18N.en[key];
        }
    });

    // 2. Update placeholder of all [data-i18n-placeholder] elements
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });

    // 3. Update title and aria-label of all [data-i18n-title] elements
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key]) {
            el.title = dict[key];
            el.setAttribute('aria-label', dict[key]);
        }
    });

    // 4. Synchronize Language Selectors
    const langSelect = document.getElementById('lang-select');
    if (langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }
    const voiceSelect = document.getElementById('voice-lang-select');
    if (voiceSelect && (lang === 'en' || lang === 'hi' || lang === 'ne' || lang === 'as')) {
        voiceSelect.value = lang;
    }
    const voiceSelectModal = document.getElementById('voice-lang-select-modal');
    if (voiceSelectModal && (lang === 'en' || lang === 'hi' || lang === 'ne' || lang === 'as')) {
        voiceSelectModal.value = lang;
    }

    // 5. Update legacy element IDs for backwards compatibility
    const el = function(id) { return document.getElementById(id); };
    if (el('lbl-goi')) el('lbl-goi').innerText = dict.goi;
    if (el('lbl-ministry')) el('lbl-ministry').innerText = dict.ministry;
    if (el('lbl-sync')) el('lbl-sync').innerText = dict.sync;
    if (el('lbl-queue-title')) el('lbl-queue-title').innerText = dict.queue_title;
    if (el('lbl-protocol')) el('lbl-protocol').innerText = dict.rec_protocol;
    if (el('btn-auth')) el('btn-auth').innerText = dict.auth_protocol;
    if (el('btn-issue-alert')) el('btn-issue-alert').innerText = dict.issue_alert;
    if (el('card-action-title')) el('card-action-title').innerText = dict.rec_protocol;

    // 6. Re-render dynamic components if available
    if (typeof window.renderReportsTable === 'function') {
        window.renderReportsTable();
    }
    if (typeof window.updateSectorHUD === 'function' && window.getCurrent3DSector) {
        window.updateSectorHUD(window.getCurrent3DSector());
    }

    console.log('[I18N] Portal language updated to:', lang);
}

function speakEmergencyAlert(messageKey, lang = 'en') {
    if ('speechSynthesis' in window) {
        const activeLang = lang || currentPortalLang || localStorage.getItem('parvat_lang') || 'en';
        const text = PARVAT_I18N[activeLang]?.[messageKey] || PARVAT_I18N['en'][messageKey] || messageKey;
        
        window.speechSynthesis.cancel();
        window.speechSynthesis.resume();

        const utterance = new SpeechSynthesisUtterance(text);
        utterance.lang = activeLang === 'hi' ? 'hi-IN' : (activeLang === 'ne' ? 'ne-NP' : (activeLang === 'as' ? 'as-IN' : 'en-US'));
        utterance.rate = 0.88;
        utterance.pitch = 1.08;
        utterance.volume = 1.0;

        if (typeof window.playBroadcastAttentionTone === 'function') {
            window.playBroadcastAttentionTone(function() {
                window.speechSynthesis.speak(utterance);
            });
        } else {
            window.speechSynthesis.speak(utterance);
        }
        
        if (typeof window.showToast === 'function') {
            window.showToast('Voice advisory broadcasting in ' + activeLang.toUpperCase() + ' (300% MEGA BOOST)', 'error');
        }
    }
}

